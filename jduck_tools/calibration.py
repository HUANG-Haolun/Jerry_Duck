"""Joint calibration data: ADC <-> URDF joint angle, and URDF limit patching.

Per joint:
    q   = sign * (adc - adc_zero) * k          # rad, URDF convention
    adc = adc_zero + sign * q / k

`adc_zero` is the ADC reading with the joint at its URDF 0 pose. `sign` is +1 when
moving towards the URDF positive direction increases the ADC.
"""

from __future__ import annotations

import math
import re
import shutil
from dataclasses import asdict, dataclass, field
from pathlib import Path

import yaml

DEFAULT_K = 2 * math.pi / 1024     # rad per ADC count (1024 counts / 360°, per the spec)
DEFAULT_MARGIN = math.radians(5.0)
WINDOW_WARN = (60, 940)            # firmware clamps targets to 50..950

# microduck / jduck_mjcf joint order. URDF names add a "_joint" suffix.
JOINTS = [
    "left_hip_yaw", "left_hip_roll", "left_hip_pitch", "left_knee", "left_ankle",
    "neck_pitch", "head_pitch", "head_yaw", "head_roll",
    "right_hip_yaw", "right_hip_roll", "right_hip_pitch", "right_knee", "right_ankle",
]


@dataclass
class JointCal:
    id: int
    adc_zero: int | None = None
    sign: int | None = None
    adc_min: int | None = None
    adc_max: int | None = None
    jumps: int = 0          # suspicious discontinuities seen during the sweep

    @property
    def complete(self) -> bool:
        return None not in (self.adc_zero, self.sign, self.adc_min, self.adc_max)

    def to_rad(self, adc: float, k: float) -> float:
        return self.sign * (adc - self.adc_zero) * k

    def to_adc(self, q: float, k: float) -> float:
        return self.adc_zero + self.sign * q / k

    def urdf_range(self, k: float, margin: float) -> tuple[float, float]:
        qa, qb = self.to_rad(self.adc_min, k), self.to_rad(self.adc_max, k)
        return min(qa, qb) + margin, max(qa, qb) - margin


@dataclass
class Calibration:
    k_rad_per_count: float = DEFAULT_K
    margin_rad: float = DEFAULT_MARGIN
    joints: dict[str, JointCal] = field(default_factory=dict)

    @classmethod
    def load(cls, path: Path) -> "Calibration":
        if not path.exists():
            return cls()
        data = yaml.safe_load(path.read_text()) or {}
        return cls(
            k_rad_per_count=float(data.get("k_rad_per_count", DEFAULT_K)),
            margin_rad=float(data.get("margin_rad", DEFAULT_MARGIN)),
            joints={n: JointCal(**v) for n, v in (data.get("joints") or {}).items()},
        )

    def save(self, path: Path) -> None:
        data = {
            "k_rad_per_count": self.k_rad_per_count,
            "margin_rad": self.margin_rad,
            "joints": {n: asdict(self.joints[n]) for n in JOINTS if n in self.joints},
        }
        header = (
            "# jduck joint calibration (generated by jduck_tools/calibrate.py)\n"
            "# q_rad = sign * (adc - adc_zero) * k_rad_per_count   (URDF convention)\n"
            "# Re-calibrate a joint whenever its servo horn is removed/re-seated.\n"
        )
        path.write_text(header + yaml.safe_dump(data, sort_keys=False))

    def warnings(self) -> list[str]:
        out = []
        for n in JOINTS:
            c = self.joints.get(n)
            if c is None or not c.complete:
                out.append(f"{n}: 未完成标定")
                continue
            if c.adc_min < WINDOW_WARN[0] or c.adc_max > WINDOW_WARN[1]:
                out.append(f"{n}: ADC 范围 [{c.adc_min}, {c.adc_max}] 超出固件窗口 50–950 附近，"
                           "把舵盘挪一个齿重装")
            if c.jumps:
                out.append(f"{n}: 扫动时出现 {c.jumps} 次读数跳变，可能经过电位器盲区")
            lo, hi = c.urdf_range(self.k_rad_per_count, self.margin_rad)
            if not lo < 0 < hi:
                out.append(f"{n}: URDF 零位不在可用范围 [{lo:+.3f}, {hi:+.3f}] 内，检查零位/方向")
        return out


def load_servo_map(path: Path) -> dict[str, int]:
    data = yaml.safe_load(path.read_text()) or {}
    servo_map = {str(k): int(v) for k, v in (data.get("servo_ids") or {}).items()}
    unknown = set(servo_map) - set(JOINTS)
    if unknown:
        raise ValueError(f"servo_map 里有未知关节名: {sorted(unknown)}")
    ids = list(servo_map.values())
    if len(ids) != len(set(ids)):
        raise ValueError("servo_map 里有重复的舵机 ID")
    return servo_map


def read_urdf_limits(urdf: Path) -> dict[str, tuple[float, float]]:
    text = urdf.read_text()
    out = {}
    for n in JOINTS:
        m = re.search(rf'<joint\s+name="{n}_joint".*?</joint>', text, re.S)
        if m:
            lo = re.search(r'lower="([^"]+)"', m.group(0))
            hi = re.search(r'upper="([^"]+)"', m.group(0))
            if lo and hi:
                out[n] = (float(lo.group(1)), float(hi.group(1)))
    return out


def apply_to_urdf(cal: Calibration, urdf: Path) -> list[str]:
    """Rewrite <limit lower/upper> of every calibrated joint. Keeps CRLF line endings.

    Backs the URDF up to <name>.urdf.precal.bak first (only if no backup exists yet).
    """
    backup = urdf.with_suffix(".urdf.precal.bak")
    if not backup.exists():
        shutil.copy2(urdf, backup)
    with open(urdf, newline="") as f:
        text = f.read()
    changed = []
    for n in JOINTS:
        c = cal.joints.get(n)
        if c is None or not c.complete:
            continue
        lo, hi = c.urdf_range(cal.k_rad_per_count, cal.margin_rad)
        pat = re.compile(rf'(<joint\s+name="{n}_joint".*?</joint>)', re.S)
        m = pat.search(text)
        if not m:
            continue
        block = re.sub(r'lower="[^"]*"', f'lower="{lo:.4f}"', m.group(1), count=1)
        block = re.sub(r'upper="[^"]*"', f'upper="{hi:.4f}"', block, count=1)
        text = text[:m.start()] + block + text[m.end():]
        changed.append(n)
    with open(urdf, "w", newline="") as f:
        f.write(text)
    return changed
